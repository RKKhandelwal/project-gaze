-- 8) public_id GENERATORS + TRIGGERS
-- =============================================================================

-- LOCATION public_id: loc-<slug(name)>[-<id>]
CREATE OR REPLACE FUNCTION public.set_location_public_id()
RETURNS TRIGGER AS $$
DECLARE
  base_slug text;
BEGIN
  IF NEW.public_id IS NULL OR NEW.public_id = '' THEN
    base_slug := slugify(NEW.name);
    IF base_slug = '' THEN
      base_slug := 'location';
    END IF;

    NEW.public_id := 'loc-' || base_slug;

    -- Ensure uniqueness; append internal id if collision.
    IF EXISTS (SELECT 1 FROM locations l WHERE l.public_id = NEW.public_id) THEN
      NEW.public_id := 'loc-' || base_slug || '-' || NEW.id::text;
    END IF;
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_locations_public_id ON locations;
CREATE TRIGGER trg_locations_public_id
BEFORE INSERT ON locations
FOR EACH ROW
EXECUTE FUNCTION public.set_location_public_id();


-- COURT public_id: court-<location_public_id>-<number>
CREATE OR REPLACE FUNCTION public.set_court_public_id()
RETURNS TRIGGER AS $$
DECLARE
  loc_pub text;
BEGIN
  IF NEW.public_id IS NULL OR NEW.public_id = '' THEN
    SELECT public_id INTO loc_pub FROM locations WHERE id = NEW.location_id;
    IF loc_pub IS NULL THEN
      loc_pub := 'loc';
    END IF;
    NEW.public_id := 'court-' || loc_pub || '-' || NEW.number::text;
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_courts_public_id ON courts;
CREATE TRIGGER trg_courts_public_id
BEFORE INSERT ON courts
FOR EACH ROW
EXECUTE FUNCTION public.set_court_public_id();


-- SENSOR public_id: sensor-<id> by default
CREATE OR REPLACE FUNCTION public.set_sensor_public_id()
RETURNS TRIGGER AS $$
BEGIN
  IF NEW.public_id IS NULL OR NEW.public_id = '' THEN
    NEW.public_id := 'sensor-' || NEW.id::text;
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_sensors_public_id ON sensors;
CREATE TRIGGER trg_sensors_public_id
BEFORE INSERT ON sensors
FOR EACH ROW
EXECUTE FUNCTION public.set_sensor_public_id();


